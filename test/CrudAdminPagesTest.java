import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import org.junit.*;

import play.mvc.Http.Response;

import models.forum.Category;

/** Rows and field descriptors of app/views/admin/AdminCategories/list.html: see TemplateStandIns.java. */

/**
 * Coverage of app/views/admin/AdminForums/list.html and app/views/admin/AdminCategories/list.html, the
 * two CRUD list templates the application overrides.
 *
 * The crud module mounts its routes at /admin (conf/routes: * /admin module:crud) and its generated
 * route table sends GET /admin/{type.controllerName} to {controller}.list, where controllerName is the
 * lowercased CRUD$ObjectType.name (modules/crud/app/controllers/CRUD.java): /admin/adminforums ->
 * AdminForums.list, /admin/admincategories -> AdminCategories.list. Both controllers are
 * @With(Secure.class) + @Check(Profile.ADMINISTRATOR), so the pages are fetched as
 * admin@domain.com; a non-administrator gets errors/403.html and an anonymous visitor is redirected to
 * /login.
 *
 * AdminCategories.list cannot be reached by a request: app/views/admin/AdminCategories/list.html asks
 * for #{crud.table fields:['name', 'description', 'forums']}, and the table tag reads
 * _caller.type.getField(field).type for every field after the first, which is a NullPointerException
 * on the "description" the entity does not have (models.forum.Category has name, displayOrder and
 * forums only). One case shows that a real administrator request fails, and the markup of the
 * template is produced by a direct render driven by TemplateStandIns.CategoryObjectType and
 * TemplateStandIns.CategoryRow, which supply the missing field and its descriptor.
 *
 * The markup asserted below is the CRUD module's layout and tags plus what our templates put inside
 * it, so the assertions pin the ids and links of our files: crudList, crudListTitle, crudListSearch,
 * crudListTable, crudListPagination and crudListAdd. @{blank()} is the module's blank action, which
 * reverses to /admin/{controllerName}/new, and @{list()} to /admin/{controllerName}.
 */
public class CrudAdminPagesTest extends BaseForumViewTest {

	private static final String CRUD_FOOTER = "<div id=\"crudFooter\"> Generated by the Play CRUD module. "
			+ "<a href=\"https://www.playframework.com/documentation/1.1/crud\">Learn how to customize it !</a> </div>";

	// ~~~~~~~~~~~~ admin/AdminForums/list.html, reached by real requests

	@Test
	public void adminForumsPageListsTheForumsWithTwoFields() throws Throwable {
		clearCookies();
		login("admin@domain.com", "secret");
		Response response = GET("/admin/adminforums");
		assertStatus(200, response);
		String body = markup(response);

		assertContains("<div id=\"crudList\" class=\"AdminForums\">", body);
		assertContains("<h2 id=\"crudListTitle\">AdminForums</h2>", body);
		assertContains("<div id=\"crudListSearch\">", body);
		assertContains("<div id=\"crudListTable\">", body);
		assertContains("<div id=\"crudListPagination\">", body);
		assertContains("<p id=\"crudListAdd\"> <a href=\"/admin/adminforums/new\">Add Forum</a> </p>", body);
		assertContains(CRUD_FOOTER, body);

		// #{crud.table fields:['name', 'description']}: name is the first column and links to show(id)
		assertContains("<th> <a class=\"\" href=\"/admin/adminforums?orderBy=name&order=ASC\"> name </a> </th> "
				+ "<th> <a class=\"\" href=\"/admin/adminforums?orderBy=description&order=ASC\"> description </a> </th>", body);
		assertNotContains("<th> <a class=\"\" href=\"/admin/adminforums?orderBy=forums&order=ASC\"> forums </a> </th>", body);

		// the five fixture forums, in the odd/even rows the table tag writes
		assertContains("<tr class=\"odd\"> <td> <a href=\"/admin/adminforums/1\">mainForum1</a> </td> <td> Main forum 1 description </td> </tr>", body);
		assertContains("<tr class=\"even\"> <td> <a href=\"/admin/adminforums/2\">mainForum2</a> </td> <td> Main forum 2 description </td> </tr>", body);
		assertContains("<tr class=\"odd\"> <td> <a href=\"/admin/adminforums/3\">modoForum1</a> </td> <td> Moderators forum 1 description </td> </tr>", body);
		assertContains("<tr class=\"even\"> <td> <a href=\"/admin/adminforums/4\">modoForum2</a> </td> <td> Moderators forum 2 description </td> </tr>", body);
		assertContains("<tr class=\"odd\"> <td> <a href=\"/admin/adminforums/5\">Home Page</a> </td> <td> News, shown on the home page </td> </tr>", body);

		// 5 objects, fewer than crud.pageSize -> #{crud.pagination} writes no page list
		assertContains("<p class=\"crudCount\"> 5 AdminForums </p>", body);
		assertNotContains("<p class=\"crudPages\">", body);

		// CRUD/layout.html has its own header, so no main.html nav bar appears on this page
		assertContains("<div id=\"crudHeader\"> <h1><a href=\"/admin/\">Administration</a></h1> </div>", body);
		assertContains("<div id=\"crudBreadcrumb\"> <ul> <li><a href=\"/admin/\">Home</a></li> "
				+ "<li>&gt; <a href=\"/admin/adminforums\">AdminForums</a></li> </ul> </div>", body);
		assertNotContains("<li><a href=\"/\">News</a></li>", body);
	}

	@Test
	public void adminForumsPageSearchesAndShowsTheTotalSizeLink() throws Throwable {
		clearCookies();
		login("admin@domain.com", "secret");
		Response response = GET("/admin/adminforums?search=main&searchFields=name+description");
		assertStatus(200, response);
		String body = markup(response);

		// #{crud.search} fills the box with params.search and adds the total link because it is set
		assertContains("<input type=\"text\" name=\"search\" value=\"main\" /> <input type=\"submit\" value="
				+ "\"Search\" /> (<a href=\"/admin/adminforums\">5 total</a>)", body);
		// the search keeps the orderBy links of the table head
		assertContains("<th> <a class=\"\" href=\"/admin/adminforums?orderBy=name&search=main&order=ASC\"> name </a> </th>", body);
		// count is the filtered size, totalCount the whole table
		assertContains("<p class=\"crudCount\"> 2 AdminForums </p>", body);
		assertContains("<tr class=\"odd\"> <td> <a href=\"/admin/adminforums/1\">mainForum1</a> </td>", body);
		assertContains("<tr class=\"even\"> <td> <a href=\"/admin/adminforums/2\">mainForum2</a> </td>", body);
		assertNotContains("modoForum1", body);
	}

	@Test
	public void adminForumsPageMarksTheSortedColumnAndListsNothingOnAFarPage() throws Throwable {
		clearCookies();
		login("admin@domain.com", "secret");
		Response response = GET("/admin/adminforums?orderBy=name&order=DESC&page=2");
		assertStatus(200, response);
		String body = markup(response);

		// orderBy == name and order == DESC -> the table tag writes crudSortedDesc and the link asks for ASC
		assertContains("<th> <a class=\"crudSortedDesc\" href=\"/admin/adminforums?orderBy=name&order=ASC\"> name </a> </th>", body);
		assertContains("<th> <a class=\"\" href=\"/admin/adminforums?orderBy=description&order=ASC\"> description </a> </th>", body);
		// page 2 of 5 objects with pageSize 30 -> #{list objects} renders no row but the head stays
		assertContains("<thead> <tr>", body);
		assertNotContains("<tr class=\"odd\">", body);
		assertNotContains("<tr class=\"even\">", body);
		assertContains("<p class=\"crudCount\"> 5 AdminForums </p>", body);
	}

	// ~~~~~~~~~~~~ admin/AdminCategories/list.html, only reachable by a direct render

	@Test
	public void adminCategoriesPageCannotBeRenderedByARequestBecauseTheEntityHasNoDescription() throws Throwable {
		clearCookies();
		login("admin@domain.com", "secret");
		try {
		GET("/admin/admincategories");
			Assert.fail("expected the missing description field to break #{crud.table}");
		} catch (Throwable t) {
			// modules/crud/app/views/tags/crud/table.html: _caller.type.getField('description') is null
			Assert.assertTrue("unexpected: " + t.getMessage(),
					t.getMessage().contains("Cannot get property 'type' on null object"));
		}
	}

	private static Map<String, Object> adminCategoriesArgs(int page, int count, int totalCount, String orderBy,
			String order, String search) throws Throwable {
		// A fresh binding for every render: renderView() puts the outer thread-locals back afterwards
		Map<String, Object> args = viewArgs("admin@domain.com", "/admin/admincategories");
		play.mvc.Http.Request request = (play.mvc.Http.Request) args.get("request");
		request.controller = "admin.AdminCategories";
		request.actionMethod = "list";

		TemplateStandIns.CategoryObjectType type = new TemplateStandIns.CategoryObjectType(Category.class);
		type.name = "AdminCategories";
		type.controllerName = "admincategories";
		type.controllerClass = controllers.admin.AdminCategories.class;

		List<Object> rows = new ArrayList<Object>();
		rows.add(TemplateStandIns.crudRow(2L, "Main Category", "Main category description"));
		rows.add(TemplateStandIns.crudRow(3L, "Moderators Category", null));

		args.put("type", type);
		args.put("objects", rows);
		args.put("count", count);
		args.put("totalCount", totalCount);
		args.put("page", page);
		args.put("orderBy", orderBy);
		args.put("order", order);
		if (search != null) {
			((play.mvc.Scope.Params) args.get("params")).put("search", search);
		}
		return args;
	}

	@Test
	public void adminCategoriesPageListsTheThreeFieldsOfTheTable() throws Throwable {
		String body = renderView("admin/AdminCategories/list.html", adminCategoriesArgs(1, 2, 2, null, null, null));

		// CRUD/layout.html breadcrumbs, which name the type the renderArgs carry
		assertContains("<div id=\"crudBreadcrumb\"> <ul> <li><a href=\"/admin/\">Home</a></li> "
				+ "<li>&gt; <a href=\"/admin/admincategories\">AdminCategories</a></li> </ul> </div>", body);
		assertContains("<div id=\"crudList\" class=\"AdminCategories\">", body);
		assertContains("<h2 id=\"crudListTitle\">AdminCategories</h2>", body);
		assertContains("<form action=\"/admin/admincategories\" method=\"get\" accept-charset=\"utf-8\" enctype=\"application/x-www-form-urlencoded\" > <input type=\"text\" name=\"search\" value=\"\" /> <input type=\"submit\" value=\"Search\" /> </form>", body);
		assertContains("<p id=\"crudListAdd\"> <a href=\"/admin/admincategories/new\">Add Category</a> </p>", body);
		assertContains(CRUD_FOOTER, body);

		// the three fields: the descriptor the entity lacks is the one CategoryObjectType synthesizes
		assertContains("<th> <a class=\"\" href=\"/admin/admincategories?orderBy=name&order=ASC\"> name </a> </th> "
				+ "<th> <a class=\"\" href=\"/admin/admincategories?orderBy=description&order=ASC\"> description </a> </th> "
				+ "<th> <a class=\"\" href=\"/admin/admincategories?orderBy=forums&order=ASC\"> forums </a> </th>", body);

		// a description that is present, and one that is null -> an empty cell
		assertContains("<tr class=\"odd\"> <td> <a href=\"/admin/admincategories/2\">Main Category</a> </td> <td> Main category description </td> <td> [] </td> </tr>", body);
		assertContains("<tr class=\"even\"> <td> <a href=\"/admin/admincategories/3\">Moderators Category</a> </td> <td> </td> <td> [] </td> </tr>", body);
		assertContains("<p class=\"crudCount\"> 2 AdminCategories </p>", body);
		assertNotContains("<p class=\"crudPages\">", body);
	}

	@Test
	public void adminCategoriesPageSearchesAndPaginatesAndMarksTheSortedColumn() throws Throwable {
		// 31 objects over pageSize 30 -> two pages, and the caller is on the second one
		String body = renderView("admin/AdminCategories/list.html",
				adminCategoriesArgs(2, 31, 31, "name", "DESC", "Main"));

		assertContains("<input type=\"text\" name=\"search\" value=\"Main\" /> <input type="
				+ "\"submit\" value=\"Search\" /> (<a href=\"/admin/admincategories\">31 total</a>)", body);
		assertContains("<th> <a class=\"crudSortedDesc\" href=\"/admin/admincategories?orderBy=name&search=Main&order=ASC\"> name </a> </th>", body);
		assertContains("<th> <a class=\"\" href=\"/admin/admincategories?orderBy=description&search=Main&order=ASC\"> description </a> </th>", body);
		assertContains("<th> <a class=\"\" href=\"/admin/admincategories?orderBy=forums&search=Main&order=ASC\"> forums </a> </th>", body);
		assertContains("<p class=\"crudCount\"> 31 AdminCategories </p>", body);

		// #{crud.pagination}: the active page is a <strong>, the others are links, plus a previous link
		assertMatches("<span class=\"previous\"> <a href=\"/admin/admincategories\\?orderBy=name&search=Main&page=1&order=DESC\" >. Previous</a> </span>", body);
		assertContains("<span class=\"page\"> <a href=\"/admin/admincategories?orderBy=name&search=Main&page=1&order=DESC\" >1</a> </span>", body);
		assertContains("<span class=\"page\"> <strong>2</strong> </span>", body);
	}

	@Test
	public void theCrudIndexPageListsBothControllers() throws Throwable {
		clearCookies();
		login("admin@domain.com", "secret");
		Response response = GET("/admin");
		assertStatus(200, response);
		String body = markup(response);

		// CRUD.index is the module's own page, but it is what the Administration item of main.html links
		assertContains("<h2>Choose the object to edit</h2>", body);
		assertContains("<a href=\"/admin/admincategories\">AdminCategories</a>", body);
		assertContains("<a href=\"/admin/adminforums\">AdminForums</a>", body);
		Assert.assertEquals(7, tableRows(body).size());
		assertContains("<td class=\"crudNew\" > <a href=\"/admin/adminforums/new\">Add</a> </td>", body);
		assertContains(CRUD_FOOTER, body);
	}

	@Test
	public void anAdministratorIsNeededForBothPages() throws Throwable {
		// Nobody logged in: Secure.checkAccess() redirects to /login
		clearCookies();
		Response response = GET("/admin/adminforums");
		assertStatus(302, response);
		assertLocation(response, "/login");

		// A logged-in non-administrator gets errors/403.html (see ErrorPagesTest for its content)
		clearCookies();
		login("modo@domain.com", "secret");
		assertStatus(403, GET("/admin/adminforums"));
		assertStatus(403, GET("/admin/admincategories"));
	}
}
