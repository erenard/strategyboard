	/**
	 * The help span tags/crud/form.html writes under every field. A field whose annotation list is empty
	 * renders "${field.help()}" as nothing, so the tags are separated by one space, which is what the
	 * whitespace-collapsed body keeps.
	 */
	private static String helpSpan(String help) {
		return "<span class=\"crudHelp\">" + (help.isEmpty() ? " " : " " + help + " ") + "</span>";
	}

