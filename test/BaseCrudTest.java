/**
 * Setup shared by the seven suites that drive the CRUD module through /admin:
 * CrudAdminUsersTest, CrudAdminUserGroupsTest, CrudAdminPermissionsTest, CrudAdminTopicsTest,
 * CrudAdminAttachmentsTest, CrudAdminCategoriesTest and CrudAdminForumsTest.
 *
 * conf/routes mounts the module at /admin ({module:crud}), and modules/crud/conf/routes generates one
 * route set per CRUD$ObjectType, so /admin/adminusers/new is AdminUsers.blank,
 * /admin/adminusers/{id} is AdminUsers.show, POST /admin/adminusers is create,
 * POST /admin/adminusers/{id} is save, DELETE /admin/adminusers/{id} is delete and
 * GET /admin/adminusers/{id}/{field} is attachment. Every app controller is @With(Secure.class) +
 * @Check(Profile.ADMINISTRATOR), so all requests below are made as admin@domain.com; the anonymous and
 * non-administrator cases are covered by CrudAdminPagesTest and CrudIndexForbiddenTest.
 *
 * The markup asserted here is the module's own CRUD/blank.html, CRUD/show.html, CRUD/list.html,
 * CRUD/layout.html and tags/crud/*.html, because app/views overrides only
 * admin/AdminForums/list.html and admin/AdminCategories/list.html. CRUD.list, CRUD.show and CRUD.blank
 * catch the TemplateNotFoundException their render() raises and fall back to the module templates, which
 * is why the five controllers without an override get module markup.
 *
 * Five behaviors of the module are relied on and asserted by the suites:
 *   - Validation errors are not kept in a cookie: CRUD.save and CRUD.create never call
 *     validation.keep(), so PLAY_ERRORS stays empty while the errors appear inline as
 *     class="hasError" plus <span class="error">...</span>, and renderArgs.error
 *     (messages.get('crud.hasErrors')) prints the "Please correct errors" box.
 *   - Fields whose entity property is a one-to-many collection get ObjectField.type "unknown"
 *     (models.forum.UserGroup.permissions, Category.forums, Forum.topics, Topic.posts), so
 *     tags/crud/form.html renders a bare <div class="crudField crud_unknown"> with no label and no
 *     input. Posting object.posts.id therefore changes nothing.
 *   - CRUD.delete redirects from inside its catch block, so flash.success("The X has been deleted") is
 *     never reached on a foreign-key failure: the flash stays "Cannot delete this object" and the
 *     Location is show(id), not the list.
 *   - A controller method called from another controller method is turned into a redirect by
 *     ControllersEnhancer, which is why CRUD actions always answer 302 + Location instead of rendering
 *     the page they redirect to.
 *   - CRUD.list reads request.args.get("where"), but a query string lands in request.params, so
 *     ?where=... never reaches the JPQL condition and cannot filter a list page.
 */
