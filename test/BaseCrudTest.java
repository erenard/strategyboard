	/**
	 * crud.relationField: the placeholder option, then one option per row of the related table given as
	 * id, label, id, label... selectedId gets selected="true".
	 *
	 * @param placeholder "(Please select a value)" when the relation is @Required, "(None)" when it is not
	 */
	protected static void assertRelationField(String body, String field, String placeholder, String help,
			String selectedId, String... idAndLabel) {
		assertContains(relationBlock(field, placeholder, help, selectedId, null, idAndLabel), body);
	}

	protected static void assertRelationFieldError(String body, String field, String placeholder, String help,
			String message, String selectedId, String... idAndLabel) {
		assertContains(relationBlock(field, placeholder, help, selectedId, message, idAndLabel), body);
	}

	private static String relationBlock(String field, String placeholder, String help, String selectedId,
			String message, String... idAndLabel) {
		StringBuilder block = new StringBuilder("<div class=\"crudField crud_relation\"> <label for=\"object_" + field
				+ "\"> " + field + " </label> <select id=\"object_" + field + "\" name=\"object." + field + ".id\"> "
				+ "<option value=\"\">" + placeholder + "</option>");
		for (int i = 0; i < idAndLabel.length; i += 2) {
			boolean selected = selectedId != null && selectedId.equals(idAndLabel[i]);
			block.append(" <option value=\"" + idAndLabel[i] + "\"" + (selected ? " selected=\"true\"" : " ") + ">"
					+ idAndLabel[i + 1] + "</option>");
		}
		block.append(" </select>");
		if (message != null) {
			block.append(" <span class=\"error\">" + message + "</span>");
		}
		block.append(" " + helpSpan(help) + " </div>");
		return block.toString();
	}

